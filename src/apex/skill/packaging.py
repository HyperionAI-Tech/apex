"""Harness packages generated from the canonical skill folder (`packaging/`, never hand-edited).

- `packaging/claude-plugin/`: a Claude Code plugin bundling the skill and the MCP server.
- `packaging/gemini-extension/`: a Gemini CLI extension with the MCP server and the skill.

Regenerate with `uv run python -m apex.skill.packaging`; a test fails when the committed output
drifts from the canonical folder.
"""

import json
import shutil
import sys
from pathlib import Path

from apex import __version__
from apex.skill.install import SKILL_NAME, skill_source

DESCRIPTION = (
    "Formally verify Python functions with Lean 4: proven / refuted / gap verdicts from Apex."
)
SERVER = {"command": "apex", "args": ["mcp"]}


def _skill_copy(dst: Path) -> None:
    shutil.copytree(
        skill_source(), dst / "skills" / SKILL_NAME, ignore=shutil.ignore_patterns("__pycache__")
    )


def _write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n")


def build(out: Path) -> list[Path]:
    if out.exists():
        shutil.rmtree(out)
    plugin = out / "claude-plugin"
    _write_json(
        plugin / ".claude-plugin" / "plugin.json",
        {
            "name": SKILL_NAME,
            "version": __version__,
            "description": DESCRIPTION,
            "author": {"name": "hyperion-ai"},
        },
    )
    _write_json(plugin / ".mcp.json", {"mcpServers": {"apex": SERVER}})
    _skill_copy(plugin)
    gemini = out / "gemini-extension"
    _write_json(
        gemini / "gemini-extension.json",
        {"name": SKILL_NAME, "version": __version__, "mcpServers": {"apex": SERVER}},
    )
    _skill_copy(gemini)
    readme = (
        "Generated by `uv run python -m apex.skill.packaging` from skill/apex-verify/. "
        "Do not edit; edit the canonical skill and regenerate.\n\n"
        "Both packages start the server with `apex mcp`, so Apex must be installed "
        "(`uv tool install ...`) and on PATH.\n"
    )
    (out / "README.md").write_text(readme)
    return sorted(p for p in out.rglob("*") if p.is_file())


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[3]
    for p in build(Path(sys.argv[1]) if len(sys.argv) > 1 else root / "packaging"):
        print(p)
